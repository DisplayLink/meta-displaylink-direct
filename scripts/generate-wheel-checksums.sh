#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 2 ]]; then
    echo "Missing arguments. Usage: $0 <tag> <version>" >&2
    echo "Example: $0 v2.0.0 2.0.0+g287e926058.build4" >&2
    exit 1
fi

TAG="$1"
VERSION="$2"

RELEASE_URL="https://github.com/DisplayLink/displaylink-direct/releases/download/${TAG}"
OUTPUT="recipes-dlsdk/python3-dlsdk/python3-dlsdk-wheel-checksums_${TAG#v}.inc"

ABIS=(cp310 cp311 cp312 cp313 cp314)
ARCHS=(aarch64 x86_64)

tmp_dir="$(mktemp -d)"
tmp_output="$(mktemp "$OUTPUT".tmp.XXXXXX)"

cleanup() {
    rm -rf -- "$tmp_dir"
    if [[ -n "$tmp_output" ]]; then
        rm -f -- "$tmp_output"
    fi
}
trap cleanup EXIT

{
    printf '# Checksums for DisplayLink Direct %s\n' "$VERSION"
    printf '# Auto-generated by generate-wheel-checksums.sh. Do not edit!\n\n'

    # Generate hash for every ABI and architecture combination
    for abi in "${ABIS[@]}"; do
        for arch in "${ARCHS[@]}"; do
            wheel="dlsdk-${VERSION}-${abi}-${abi}-manylinux_2_31_${arch}.whl"
            wheel_path="${tmp_dir}/${wheel}"

            echo "Downloading ${wheel}..." >&2
            curl -fLsS "${RELEASE_URL}/${wheel}" -o "$wheel_path"

            checksum=$(sha256sum "$wheel_path" | cut -d' ' -f1)
            printf 'WHEEL_SHA256_%s_%s = "%s"\n' "$abi" "$arch" "$checksum"
        done
        printf '\n'
    done

} > "$tmp_output"

mv -f -- "$tmp_output" "$OUTPUT"
tmp_output=""

echo "Finished generating ${OUTPUT}"
